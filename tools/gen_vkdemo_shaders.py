#!/usr/bin/env python3
"""Compile tools/shaders/*.vert|frag (GLSL) to SPIR-V with naga and write src/commands/vkdemo_spv.h and doomport_spv.h.

  cargo install naga-cli        (once; put naga on PATH or pass NAGA=/path/to/naga)
  python3 tools/gen_vkdemo_shaders.py
"""
import os, struct, subprocess, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
naga = os.environ.get("NAGA", "naga")
SETS = {
    "vkdemo_spv.h": ("vkdemo", ("cube.vert", "cube.frag")),
}
for header, (prefix, names) in SETS.items():
    out = ["// Generated by tools/gen_vkdemo_shaders.py from tools/shaders/ (naga). Do not edit.\n"]
    for name in names:
        stage = name.rsplit(".", 1)[1]
        src = os.path.join(root, "tools", "shaders", name)
        spv = src + ".spv"
        subprocess.check_call([naga, "--input-kind", "glsl", "--shader-stage", stage, "--keep-coordinate-space",
                               "--index-bounds-check-policy", "Unchecked", src, spv])
        data = open(spv, "rb").read()
        words = struct.unpack("<%dI" % (len(data) // 4), data)
        ident = prefix + "_" + name.replace(".", "_").replace("doom_blit_", "") + "_spv"
        out.append("static const uint32_t %s[%d] = {\n" % (ident, len(words)))
        for i in range(0, len(words), 8):
            out.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",\n")
        out.append("};\n")
    open(os.path.join(root, "src", "commands", header), "w").write("".join(out))
    print("wrote src/commands/" + header)
