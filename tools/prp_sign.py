#!/usr/bin/env python3
"""Sign files for RadiumOS with a PRP (PRPSIG1) trailer. Needs the `cryptography` package.

  prp_sign.py keygen [--key keys/update.key] [--header src/commands/update_key.h]
  prp_sign.py sign FILE [--key keys/update.key] [--out FILE2]
  prp_sign.py verify FILE [--key keys/update.key]
  prp_sign.py pub [--key keys/update.key]

keygen writes the private key (keep it secret, it is git-ignored) and the public key the kernel trusts
(update_key.h). The trailer appended by `sign` is "PRPSIG1" | Ed25519 public key | R | S (103 bytes) over the file
contents, the same format the on-device PRP verifier (rust_prp_verify) reads.
"""
import argparse, os, sys

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey

MAGIC = b"PRPSIG1"
TRAILER = 7 + 32 + 64
RAW = dict(encoding=serialization.Encoding.Raw, format=serialization.PublicFormat.Raw)


def load_private(path):
    with open(path) as f:
        return Ed25519PrivateKey.from_private_bytes(bytes.fromhex(f.read().strip()))


def public_bytes(key):
    return key.public_key().public_bytes(**RAW)


def has_trailer(data):
    return len(data) >= TRAILER and data[-TRAILER:-TRAILER + 7] == MAGIC


def sign_bytes(key, data):
    if has_trailer(data):
        sys.exit("already signed")
    return data + MAGIC + public_bytes(key) + key.sign(data)


def verify_bytes(data, trusted):
    if not has_trailer(data):
        return "unsigned"
    body, tail = data[:-TRAILER], data[-TRAILER:]
    if tail[7:39] != trusted:
        return "signed by another key"
    try:
        Ed25519PublicKey.from_public_bytes(trusted).verify(tail[39:], body)
    except InvalidSignature:
        return "bad signature"
    return "ok"


def write_header(path, pub):
    rows = ["    " + ", ".join("0x%02x" % b for b in pub[i:i + 8]) + "," for i in range(0, 32, 8)]
    with open(path, "w") as f:
        f.write("// Generated by tools/prp_sign.py keygen: the Ed25519 key that online updates must be signed with.\n")
        f.write("static const uint8_t UPDATE_TRUSTED_KEY[32] = {\n" + "\n".join(rows) + "\n};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["keygen", "sign", "verify", "pub"])
    ap.add_argument("file", nargs="?")
    ap.add_argument("--key", default="keys/update.key")
    ap.add_argument("--out")
    ap.add_argument("--header", default="src/commands/update_key.h")
    args = ap.parse_args()

    if args.cmd == "keygen":
        if os.path.exists(args.key):
            sys.exit("%s exists; refusing to overwrite a signing key" % args.key)
        key = Ed25519PrivateKey.generate()
        os.makedirs(os.path.dirname(args.key) or ".", exist_ok=True)
        fd = os.open(args.key, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write(key.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
                                      serialization.NoEncryption()).hex() + "\n")
        write_header(args.header, public_bytes(key))
        print("private key: %s\npublic key:  %s (%s)" % (args.key, public_bytes(key).hex(), args.header))
    elif args.cmd == "pub":
        print(public_bytes(load_private(args.key)).hex())
    else:
        if not args.file:
            sys.exit("a FILE is required")
        with open(args.file, "rb") as f:
            data = f.read()
        if args.cmd == "sign":
            with open(args.out or args.file, "wb") as f:
                f.write(sign_bytes(load_private(args.key), data))
            print("signed", args.out or args.file)
        else:
            state = verify_bytes(data, public_bytes(load_private(args.key)))
            print(state)
            return 0 if state == "ok" else 1


if __name__ == "__main__":
    sys.exit(main())
