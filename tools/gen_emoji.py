#!/usr/bin/env python3
"""Builds src/commands/emoji_data.h (shortcode -> code points) from github/gemoji's emoji.json.

usage: tools/gen_emoji.py emoji.json src/commands/emoji_data.h
"""
import json, sys

src, dst = sys.argv[1], sys.argv[2]
defs = {}
for e in json.load(open(src)):
    hexes = "-".join("%x" % ord(c) for c in e["emoji"])   # kept with FE0F: it is what gets sent
    for name in e["aliases"]:
        defs.setdefault(name, hexes)

rows = sorted(defs.items(), key=lambda kv: (len(kv[0]), kv[0]))
with open(dst, "w") as f:
    f.write("// emoji_data.h - generated by tools/gen_emoji.py from github/gemoji; do not edit\n")
    f.write("#ifndef EMOJI_DATA_H\n#define EMOJI_DATA_H\n\n")
    f.write("typedef struct { const char *name; const char *hex; } emoji_def_t;\n\n")
    f.write("static const emoji_def_t EMOJI_DEFS[] = {\n")
    for name, hexes in rows:
        f.write('    { "%s", "%s" },\n' % (name, hexes))
    f.write("};\n")
    f.write("#define EMOJI_N ((int)(sizeof(EMOJI_DEFS) / sizeof(EMOJI_DEFS[0])))\n\n#endif\n")
print(len(rows), "shortcodes")
