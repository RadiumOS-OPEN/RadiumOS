#!/usr/bin/env python3
"""Builds src/commands/emoji_png.h: small palette PNGs of the common emoji (Twemoji artwork, CC-BY 4.0).

usage: tools/gen_emoji_png.py emoji.json src/commands/emoji_png.h [cache_dir]

The emoji.json is github/gemoji's db/emoji.json. Images come from jsDelivr's Twemoji mirror; the 72x72
originals are cached in cache_dir (default /tmp/twemoji72) so reruns are offline.
"""
import io, json, os, sys, urllib.request
from concurrent.futures import ThreadPoolExecutor
from PIL import Image

SRC, DST = sys.argv[1], sys.argv[2]
CACHE = sys.argv[3] if len(sys.argv) > 3 else "/tmp/twemoji72"
BASE = "https://cdn.jsdelivr.net/gh/jdecked/twemoji@15.1.0/assets/72x72/"
SIZE = 32
PER_CATEGORY = {"Smileys & Emotion": 999, "People & Body": 140, "Animals & Nature": 90, "Food & Drink": 70,
                "Activities": 40, "Travel & Places": 40, "Objects": 70, "Symbols": 70}
os.makedirs(CACHE, exist_ok=True)


def twemoji_name(s):
    cps = [ord(c) for c in s]
    if 0x200D not in cps:
        cps = [c for c in cps if c != 0xFE0F]
    return "-".join("%x" % c for c in cps)


picked, counts = [], {}
for e in json.load(open(SRC)):
    cat = e["category"]
    if counts.get(cat, 0) >= PER_CATEGORY.get(cat, 0):
        continue
    name = twemoji_name(e["emoji"])
    if "200d" in name:          # keep the set to single glyphs; ZWJ families are rare and fetched on demand
        continue
    counts[cat] = counts.get(cat, 0) + 1
    picked.append(name)
picked = sorted(set(picked))


def fetch(name):
    path = os.path.join(CACHE, name + ".png")
    if not os.path.exists(path):
        try:
            data = urllib.request.urlopen(BASE + name + ".png", timeout=20).read()
        except Exception:
            return name, None
        open(path, "wb").write(data)
    return name, path


with ThreadPoolExecutor(12) as pool:
    results = list(pool.map(fetch, picked))

blobs = []
for name, path in results:
    if not path:
        continue
    img = Image.open(path).convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
    img = img.quantize(colors=48, method=Image.FASTOCTREE, dither=Image.NONE)
    out = io.BytesIO()
    img.save(out, "PNG", optimize=True)
    blobs.append((name, out.getvalue()))

with open(DST, "w") as f:
    f.write("// emoji_png.h - generated by tools/gen_emoji_png.py; do not edit\n")
    f.write("// Artwork: Twemoji (c) Twitter, Inc and other contributors, licensed CC-BY 4.0.\n")
    f.write("#ifndef EMOJI_PNG_H\n#define EMOJI_PNG_H\n\n")
    f.write("typedef struct { const char *file; unsigned off; unsigned len; } emoji_png_t;\n\n")
    f.write("static const unsigned char EMOJI_PNG_DATA[] = {\n")
    off, table = 0, []
    for name, data in blobs:
        table.append((name, off, len(data)))
        off += len(data)
        for i in range(0, len(data), 24):
            f.write("    " + ",".join("0x%02x" % b for b in data[i:i + 24]) + ",\n")
    f.write("};\n\nstatic const emoji_png_t EMOJI_PNGS[] = {\n")
    for name, o, n in table:      # sorted by file name for binary search
        f.write('    { "%s", %d, %d },\n' % (name, o, n))
    f.write("};\n#define EMOJI_PNG_N ((int)(sizeof(EMOJI_PNGS) / sizeof(EMOJI_PNGS[0])))\n\n#endif\n")
print(len(blobs), "emoji,", off, "bytes of PNG")
