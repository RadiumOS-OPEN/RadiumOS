#!/usr/bin/env python3
"""Embed a JS file in C: js2c.py IN.js OUT.c SYMBOL

Writes `const char SYMBOL[]` (NUL-terminated) and `const int SYMBOL_len`.
Used for src/quickjs/dom_prelude.js; the makefile reruns it when the JS
changes. The output is committed so a build without Python still works.
"""
import sys

src, dst, sym = sys.argv[1], sys.argv[2], sys.argv[3]
data = open(src, 'rb').read()
out = ['/* Generated by tools/rbrowse/js2c.py from %s. Do not edit. */' % src.replace('\\', '/'),
       'const char %s[] =' % sym]
for line in data.splitlines(keepends=True):
    esc = ''.join(
        '\\\\' if b == 0x5C else '\\"' if b == 0x22 else '\\n' if b == 0x0A else
        '\\t' if b == 0x09 else chr(b) if 0x20 <= b < 0x7F and b != 0x3F else '\\%03o' % b
        for b in line)
    out.append('    "%s"' % esc)
out[-1] += ';'
if len(out) == 2:
    out.append('    "";')
out.append('const int %s_len = %d;' % (sym, len(data)))
open(dst, 'w').write('\n'.join(out) + '\n')
